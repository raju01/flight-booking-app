function cityKey(value: string): string {
  return value
    .replace(/\s*\([^)]*\)/g, " ")
    .replace(/\bairport\b/gi, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

export function redbusCity(value: string): RedbusCity | null {
  return CITIES[cityKey(value)] ?? null;
}
